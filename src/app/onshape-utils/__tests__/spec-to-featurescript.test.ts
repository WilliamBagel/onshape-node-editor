import { describe, it, expect } from 'vitest';
import { DefineFeatureNode } from '../../rete/nodes/definefeaturenode';
import { OutputFeatureNode } from '../../rete/nodes/outputfeaturenode';
import { assembleFeatureScriptInfo } from '../../rete/pipelineinfo';
import { FeatureStudioGenerator } from '../featurestudiogenerator';
import { btTypeToFeaturescriptType } from '../bttypetools';

describe('spec to FeatureScript emission', () => {
    it('turns a feature spec into a Feature Studio file', () => {
        // The shape `editor.ts` builds from a live Onshape feature spec, minus
        // the 1,000-line inline literal: define node + precondition specs + end.
        const define = new DefineFeatureNode({
            annotation: { type: 'Feature Type Name', value: 'My New Feature' },
            preconditions: [
                { annotation: { type: 'Property Function Name', value: 'entities' }, btType: 'BTParameterSpecQuery-174' },
                { annotation: { type: 'Property Function Name', value: 'do the thing' }, btType: 'BTParameterSpecBoolean-170' },
            ],
        });
        const output = new OutputFeatureNode();

        const info = assembleFeatureScriptInfo([
            { id: define.id, type: define.type, info: define.getFeatureScriptInfo({}) },
            { id: output.id, type: output.type, info: output.getFeatureScriptInfo({}) },
        ]);

        const code = new FeatureStudioGenerator().generateFeatureStudioCode(info);

        expect(code).toBe(
            '// Generated by Onshape Node Editor\n' +
            '// Edits will be overwritten by the Onshape Node Editor app\n' +
            'FeatureScript 2960;\n' +
            'import(path : "onshape/std/feature.fs", version : "2770.0");\n' +
            'import(path : "onshape/std/units.fs", version : "2770.0");\n' +
            '\n' +
            'annotation { "Feature Type Name" : "My New Feature" }\n' +
            'export const myNewFeature = defineFeature(function(context is Context, id is Id, definition is map)\n' +
            'precondition\n' +
            '{\n' +
            '\tannotation{"Property Function Name": "entities"}\n' +
            '\tdefinition.entities is Query;\n' +
            '\tannotation{"Property Function Name": "do the thing"}\n' +
            '\tdefinition.dothething is boolean;\n' +
            '}\n' +
            '{\n' +
            '});\n',
        );
    });

    it('maps parameter spec types to FeatureScript types', () => {
        expect(btTypeToFeaturescriptType('BTParameterSpecQuantity-173')).toBe('ValueWithUnits');
        expect(btTypeToFeaturescriptType('BTParameterSpecEnum-171')).toBe('enum');
        expect(btTypeToFeaturescriptType('BTParameterSpecBoolean-170')).toBe('boolean');
        expect(btTypeToFeaturescriptType('BTParameterSpecQuery-174')).toBe('Query');
        // unknown specs fall back to a string parameter
        expect(btTypeToFeaturescriptType('BTParameterSpecString-175')).toBe('string');
    });
});
